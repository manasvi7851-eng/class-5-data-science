import seaborn as sns
import matplotlib.pyplot as plt
data = sns.load_dataset("tips")
print(data.head(5))
print(data.info())
data = data.dropna()
sns.barplot(x = "day",y = "total_bill",hue = "sex",data = data)
plt.title("Average total bill by gender")
plt.xlabel("day")
plt.ylabel("average bill")
plt.show()
sns.countplot(x = "day",hue = "sex",data = data)
plt.title("Number of diners per day by gender")
plt.xlabel("day")
plt.ylabel("count")
plt.show()
sns.boxplot(x = "day",y = "total_bill",data = data)
plt.title("Spread of total bill per day")
plt.xlabel("day")
plt.ylabel("total_bill")
plt.show()
sns.stripplot(x = "day",y = "total_bill",data = data,jitter=True)
plt.title("Every bill amount per day")
plt.xlabel("day")
plt.ylabel("total_bill")
plt.show()
sns.swarmplot(x = "day",y = "total_bill",data = data)
plt.title("Every bill amount per day")
plt.xlabel("day")
plt.ylabel("total_bill")
plt.show()
sns.jointplot(x = "total_bill",y = "tip",data = data)
plt.suptitle("total bill versus tip")
plt.show()
sns.jointplot(x = "total_bill",y = "tip",data = data,kind = "kde")
plt.suptitle("total bill versus tip")
plt.show()
sns.jointplot(x = "total_bill",y = "tip",data = data,kind = "hex")
plt.suptitle("total bill versus tip")
plt.show()
sns.pairplot(data[["total_bill","tip","size"]])
plt.show()
sns.pointplot(x = "day",y = "total_bill",hue = "sex",data= data)
plt.show()